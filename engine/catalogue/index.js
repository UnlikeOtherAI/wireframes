'use strict';

const { documentAppearance, standardRole } = require('../design-system/resolve');
const { validateDesignSystem } = require('../design-system/validate');
const { skinPaintStyles } = require('../design-system/paint');
const { catalogueModel } = require('./model');

// The element catalogue: every element the engine knows, rendered from the
// registry that defines it. Nothing here is hand-maintained — add a registry
// entry and it appears, with its props, its example and the box rule it obeys.

const { PRIMITIVES, FAMILY_ORDER, ALIASES } = require('../schema/primitive-registry');
const { buildWireframeStyles } = require('../renderer/styles');
const { renderNode } = require('../renderer/primitives');
const { catalogueStyles } = require('./styles');
const { demoFor } = require('./demos');

const FAMILY_TITLE = {
  containers: 'Containers',
  text: 'Content',
  controls: 'Controls',
  navigation: 'Navigation',
  data: 'Data',
  feedback: 'Feedback',
};

const FRAME_NOTE = {
  S: 'always draws a box',
  C: 'the frame rules decide',
  N: 'never draws a box',
  E: 'draws one edge',
};

function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function propType(spec) {
  if (Array.isArray(spec.enum)) return spec.enum.join(' | ');
  if (spec.aliasOf) return `alias of ${spec.aliasOf}`;
  return spec.type || 'string';
}

function propsTable(entry) {
  const rows = Object.entries(entry.props || {}).map(([name, spec]) => (
    `<tr><td class="${spec.primary ? 'cat-primary' : ''}">${escapeHtml(name)}</td>`
    + `<td>${escapeHtml(propType(spec))}</td></tr>`
  ));
  if (rows.length === 0) return '<p class="cat-aliases">No props.</p>';
  return `<table class="cat-props"><thead><tr><th>Prop</th><th>Accepts</th></tr></thead>`
    + `<tbody>${rows.join('')}</tbody></table>`;
}

function aliasesFor(name) {
  const names = Array.from(ALIASES.entries())
    .filter(([, target]) => target === name)
    .map(([alias]) => `<code>${escapeHtml(alias)}</code>`);
  return names.length === 0
    ? ''
    : `<p class="cat-aliases">Also answers to ${names.join(', ')}.</p>`;
}

function renderItem(entry, options) {
  const { source, node } = demoFor(entry);
  if (options.sample?.component === entry.name && options.sample.variant !== undefined) {
    if (!(entry.props?.variant?.enum || []).includes(options.sample.variant)) throw new Error('Unknown sample variant.');
    node.props = { ...node.props, variant: options.sample.variant };
  }
  const role = standardRole(node);
  const selectAttrs = options.selectable
    ? ' data-wf-catalogue-component="' + entry.name + '" data-wf-catalogue-variant="' + (role.variant || '') + '"'
    : '';
  const demo = node ? renderNode(node, { ...options, surfaceDepth: 0 }) : '';
  const modeClass = options.mode === 'line' ? '' : ' cat-demo-dark';

  return `<article class="cat-item" id="el-${escapeHtml(entry.name)}"${selectAttrs}>
  <div class="cat-head">
    <span class="cat-name">${escapeHtml(entry.name)}</span>
    <span class="cat-frame">${escapeHtml(FRAME_NOTE[entry.frame] || '')}</span>
  </div>
  <p class="cat-summary">${escapeHtml(entry.summary)}</p>
  <div class="cat-demo${modeClass} wf wf-mode-${escapeHtml(options.mode)} wf-platform-${escapeHtml(options.platform)}">${demo}</div>
  <div class="cat-split">
    <pre class="cat-code">${escapeHtml(source)}</pre>
    <div>${propsTable(entry)}${aliasesFor(entry.name)}</div>
  </div>
</article>`;
}

function sidebar() {
  const groups = FAMILY_ORDER.map((family) => {
    const items = PRIMITIVES
      .filter((entry) => entry.family === family)
      .map((entry) => `<li><a href="#el-${escapeHtml(entry.name)}">${escapeHtml(entry.name)}</a></li>`)
      .join('');
    return `<h2>${escapeHtml(FAMILY_TITLE[family] || family)}</h2><ul>${items}</ul>`;
  }).join('');

  return `<nav class="cat-side">
  <h1>Element catalogue</h1>
  <p>${PRIMITIVES.length} elements, generated by <code>wf catalogue</code></p>
  ${groups}
</nav>`;
}

function sections(options) {
  return FAMILY_ORDER.map((family) => {
    const items = PRIMITIVES
      .filter((entry) => entry.family === family)
      .map((entry) => renderItem(entry, options))
      .join('\n');
    return `<h2 class="cat-family" id="family-${escapeHtml(family)}">${escapeHtml(FAMILY_TITLE[family] || family)}</h2>\n${items}`;
  }).join('\n');
}

/**
 * The catalogue page as a single HTML string. Pure — it reads the registry and
 * the renderer, and never touches disk.
 */
function buildCataloguePage(options = {}) {
  const mode = options.mode === 'line' ? 'line' : 'card';
  const platform = ['ios', 'android'].includes(options.platform) ? options.platform : 'web';
  const errors = options.documentMap ? validateDesignSystem(options.documentMap.manifest) : [];
  if (errors.length) throw new Error(errors[0].message);
  if (options.sample && !PRIMITIVES.some((entry) => entry.name === options.sample.component)) throw new Error('Unknown sample component.');
  const appearance = options.documentMap ? documentAppearance(options.documentMap) : { pageStyle: {} };
  const renderOptions = { mode, platform, pageStyle: {}, dataSources: {},
    ...(options.documentMap ? { ...appearance, rendering: { mode },
      viewport: { device: platform === 'web' ? 'web' : 'tablet', platform },
      sample: options.sample, selectable: true } : {}) };
  const fontAwesomeHref = options.fontAwesomeHref || './_shared/fa/css/all.min.css';

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>wf — element catalogue</title>
    <link rel="stylesheet" href="${escapeHtml(fontAwesomeHref)}" />
    <style>${catalogueStyles}</style>
    <style>${buildWireframeStyles()}</style>${renderOptions.skin ? '<style>' + skinPaintStyles + '</style>' : ''}
  </head>
  <body>
    <div class="cat-shell">
      ${sidebar()}
      <main class="cat-main">
        <div class="cat-intro">
          <h2>Every element wf can draw</h2>
          <p>Each entry below is rendered by the engine from the example beside
          it, in <code>${escapeHtml(mode)}</code> mode. The badge next to a name
          says whether that element draws a box, never draws one, or leaves the
          decision to the frame rules.</p>
          <p>This page is generated: <code>wf catalogue</code>. Adding an element
          to the registry adds it here.</p>
        </div>
        ${sections(renderOptions)}
      </main>
    </div>
  </body>
</html>`;
}

module.exports = { buildCataloguePage, catalogueModel, FAMILY_TITLE, FRAME_NOTE };
